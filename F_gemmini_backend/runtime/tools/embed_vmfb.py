#!/usr/bin/env python3
"""Turn a .vmfb into a C header holding it as a byte array.

Bare metal has no file system, so the model travels inside the binary as a
`const uint8_t[]` in .rodata. This is the same thing IREE's own
`iree_c_embed_data` build rule does.

    python3 embed_vmfb.py build/matmul.vmfb build/matmul_vmfb.h [symbol_prefix]

The optional third argument names the emitted symbols; it defaults to `vmfb`
(`vmfb_data` / `vmfb_size`). Step D and E use the default, the CNN runner
passes `cnn_vmfb`.
"""

import sys


def main(argv):
    if len(argv) not in (3, 4):
        print(__doc__)
        return 2
    src, dst = argv[1], argv[2]
    prefix = argv[3] if len(argv) == 4 else "vmfb"
    with open(src, "rb") as f:
        data = f.read()
    if not data:
        print(f"error: {src} is empty", file=sys.stderr)
        return 1

    with open(dst, "w") as f:
        f.write("// Generated by scripts/embed_vmfb.py -- do not edit.\n")
        f.write(f"// Source: {src} ({len(data)} bytes)\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write('__attribute__((aligned(64)))\n')
        f.write(f"static const uint8_t {prefix}_data[] = {{\n")
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            f.write("  " + ",".join(str(b) for b in chunk) + ",\n")
        f.write("};\n\n")
        f.write(f"static const size_t {prefix}_size = {len(data)};\n")
    print(f"embedded {len(data)} bytes -> {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
