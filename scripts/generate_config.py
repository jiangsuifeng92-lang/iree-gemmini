#!/usr/bin/env python3
"""Generate the shared compiler/kernel constants from H/config/gemmini.json."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
c = json.loads((root / "config/gemmini.json").read_text())
assert c["schema_version"] == 1
hw, limits = c["hardware"], c["kernel_limits"]
for key in ("dim", "bank_num", "bank_rows", "acc_rows"):
    if not isinstance(hw[key], int) or hw[key] <= 0:
        raise SystemExit(f"Invalid hardware field: {key}")
if hw["input_bits"] != 8 or hw["acc_bits"] != 32 or hw["dim"] != 16:
    raise SystemExit("V1 supports only the copied 16x16 int8/int32 kernel")
params = root / "F_gemmini_backend/runtime/gemmini/include/gemmini_params.h"
import re
for key, macro in (("dim", "DIM"), ("bank_num", "BANK_NUM"),
                   ("bank_rows", "BANK_ROWS"), ("acc_rows", "ACC_ROWS"),
                   ("custom_opcode", "XCUSTOM_ACC"), ("dma_max_bytes", "MAX_BYTES")):
    match = re.search(r"^#define " + macro + r"\s+(\d+)\s*$", params.read_text(), re.M)
    if not match or int(match[1]) != hw[key]:
        raise SystemExit(f"config does not match copied Gemmini SDK: {macro}")
for key, value in limits.items():
    if not isinstance(value, int) or value <= 0:
        raise SystemExit(f"Invalid kernel limit: {key}")
lines = ["/* Generated by H/scripts/generate_config.py. Do not edit. */",
         "#ifndef H_GEMMINI_CONFIG_H", "#define H_GEMMINI_CONFIG_H"]
for section in ("hardware", "kernel_limits", "planner", "layout", "epilogue"):
    for key, value in c[section].items():
        lines.append(f"#define H_GEMMINI_{key.upper()} {value}")
lines += ["#define H_GEMMINI_PLAN_ABI 1", "#endif", ""]
target = root / "include/gemmini_config.h"
contents = "\n".join(lines)
if not target.exists() or target.read_text() != contents:
    target.write_text(contents)
print(target)
